// Bundles the plugin's Lua sources (ttt/src) into the one file ttt runs:
// ttt/symbiosis/plugin.lua. ttt runs one entry file per plugin, and its
// `require` loads only ttt's own modules (ttt, ttt.editor, ...): a plugin
// cannot require a file next to it. So each source becomes a function in the
// bundle, and a small `require` in front of them loads them by name: the file
// ttt/src/core/app.lua is the module "core.app". A name that is not in the
// bundle goes to ttt's require.
//
//   bin/run-node ttt/build.ts           writes ttt/symbiosis/plugin.lua
//
// The bundle is NOT committed (git ignores it): a generated file in git
// conflicts at every merge and goes stale. Whatever uses it builds it first
// with ensureBundle(): pi when it starts, bin/setup.sh, install.ts, the tests.
import { readdirSync, readFileSync, realpathSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const SRC = join(here, 'src');
export const OUT = join(here, 'symbiosis', 'plugin.lua');
export const ENTRY = 'main';

export interface Module {
	name: string; // "core.app"
	file: string; // "ttt/src/core/app.lua", for the line map
	source: string;
}

// The .lua files under `dir`, sorted, as modules named by their path.
export function collect(dir: string = SRC, root: string = dirname(here)): Module[] {
	const out: Module[] = [];
	const walk = (d: string): void => {
		for (const entry of readdirSync(d).sort()) {
			const path = join(d, entry);
			if (statSync(path).isDirectory()) walk(path);
			else if (entry.endsWith('.lua')) {
				const name = relative(dir, path).slice(0, -'.lua'.length).split(sep).join('.');
				if (!/^[a-z_][a-z0-9_]*(\.[a-z_][a-z0-9_]*)*$/.test(name)) {
					throw new Error(`${path}: a module name is lower case words: ${name}`);
				}
				out.push({ name, file: relative(root, path).split(sep).join('/'), source: readFileSync(path, 'utf8') });
			}
		}
	};
	walk(dir);
	return out;
}

const PRELUDE = `local modules, loaded, loading = {}, {}, {}
local host_require = require
-- The bundle's require: a module in the bundle, else one of ttt's.
local function require(name)
	local value = loaded[name]
	if value ~= nil then return value end
	local load = modules[name]
	if not load then return host_require(name) end
	if loading[name] then error("modules require each other: " .. name, 2) end
	loading[name] = true
	local ok, result = pcall(load, name)
	loading[name] = nil
	if not ok then error(result, 0) end
	value = result
	if value == nil then value = true end
	loaded[name] = value
	return value
end
`;

// The bundle: a header with the line map, the prelude, each module as a
// function, and a call to the entry module.
export function bundle(modules: Module[]): string {
	const entry = modules.find((m) => m.name === ENTRY);
	if (!entry) throw new Error(`no ${ENTRY}.lua in the sources`);
	const names = new Set<string>();
	for (const m of modules) {
		if (names.has(m.name)) throw new Error(`module ${m.name} twice`);
		names.add(m.name);
		if (/^\s*module\s*\(/m.test(m.source)) throw new Error(`${m.file}: module() is not supported`);
		if (m.source.startsWith('#')) throw new Error(`${m.file}: a #! line cannot be bundled`);
	}
	const head = [
		'-- symbiosis, the ttt plugin. GENERATED by ttt/build.ts from ttt/src: do not',
		'-- edit this file; edit ttt/src and run `npm run build`.',
		'-- Lines of this file, by source (for errors in ttt\'s log):',
	];
	const body: string[] = [];
	const map: string[] = [];
	// The header's length depends on the map, which depends on the header: the
	// map has one line per module, so its length is known.
	const top = head.length + modules.length + PRELUDE.split('\n').length - 1;
	let line = top + 1;
	for (const m of modules) {
		const source = m.source.endsWith('\n') ? m.source : m.source + '\n';
		const count = source.split('\n').length - 1;
		const chunk = `modules[${JSON.stringify(m.name)}] = function(...)\n${source}end\n`;
		// The source starts on the line after `modules[...] = function`.
		map.push(`--   ${String(line + 1).padStart(5)}  ${m.file}`);
		body.push(chunk);
		line += count + 2;
	}
	return [...head, ...map, PRELUDE].join('\n') + body.join('') + `require(${JSON.stringify(ENTRY)})\n`;
}

export function build(): string {
	return bundle(collect());
}

/** Writes the bundle when the file is missing or differs. True when it wrote. */
export function ensureBundle(out: string = OUT): boolean {
	const text = build();
	try {
		if (readFileSync(out, 'utf8') === text) return false;
	} catch {}
	writeFileSync(out, text);
	return true;
}

const main = (): boolean => {
	try {
		return realpathSync(fileURLToPath(import.meta.url)) === realpathSync(process.argv[1] ?? '');
	} catch {
		return false;
	}
};

if (main()) {
	writeFileSync(OUT, build());
	console.log(`wrote ${relative(process.cwd(), OUT) || OUT}`);
}
